"""LLMProvider interface and its three implementations: Ollama, llama-server, replay."""

from __future__ import annotations

import asyncio
import json
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Protocol

import httpx


@dataclass
class LLMRequest:
    messages: list[dict[str, str]]
    schema: dict[str, Any]  # JSON schema enforced by the runtime's constrained decoding
    cache_key: str  # prompt version + alert hash (+ eval variant)
    temperature: float = 0.0
    max_tokens: int = 600


@dataclass
class LLMResponse:
    text: str
    provider: str
    model: str
    prompt_tokens: int = 0
    completion_tokens: int = 0
    latency_ms: float = 0.0
    cached: bool = False
    extra: dict[str, Any] = field(default_factory=dict)


class ProviderError(Exception):
    """The provider failed (HTTP error, bad payload, no recording). Triggers fallback."""


class ProviderTimeout(ProviderError):
    pass


class LLMProvider(Protocol):
    name: str
    model: str

    async def generate(self, request: LLMRequest) -> LLMResponse: ...

    async def aclose(self) -> None: ...


class _HttpProvider:
    name = "http"

    def __init__(self, base_url: str, model: str, timeout: float):
        self.base_url, self.model = base_url.rstrip("/"), model
        self.client = httpx.AsyncClient(timeout=httpx.Timeout(timeout, connect=5.0))

    async def _post(self, path: str, body: dict[str, Any]) -> tuple[dict[str, Any], float]:
        started = time.perf_counter()
        try:
            r = await self.client.post(f"{self.base_url}{path}", json=body)
        except httpx.TimeoutException as exc:
            raise ProviderTimeout(f"{self.name}: timed out") from exc
        except httpx.TransportError as exc:
            raise ProviderError(f"{self.name}: {exc!r}") from exc
        latency = (time.perf_counter() - started) * 1000
        if r.status_code != 200:
            raise ProviderError(f"{self.name}: HTTP {r.status_code} {r.text[:200]}")
        try:
            return r.json(), latency
        except ValueError as exc:
            raise ProviderError(f"{self.name}: non-JSON response") from exc

    async def aclose(self) -> None:
        await self.client.aclose()


class OllamaProvider(_HttpProvider):
    name = "ollama"

    def __init__(self, base_url: str, model: str, timeout: float = 90.0, num_ctx: int = 8192):
        super().__init__(base_url, model, timeout)
        self.num_ctx = num_ctx

    async def generate(self, request: LLMRequest) -> LLMResponse:
        body = {
            "model": self.model,
            "messages": request.messages,
            "stream": False,
            "format": request.schema,
            "think": False,
            "keep_alive": "30m",
            "options": {"temperature": request.temperature, "seed": 0, "num_ctx": self.num_ctx,
                        "num_predict": request.max_tokens},
        }
        data, latency = await self._post("/api/chat", body)
        try:
            text = data["message"]["content"]
        except (KeyError, TypeError) as exc:
            raise ProviderError("ollama: unexpected response shape") from exc
        return LLMResponse(text, self.name, self.model, data.get("prompt_eval_count", 0),
                           data.get("eval_count", 0), latency)


class LlamaServerProvider(_HttpProvider):
    name = "llamacpp"

    async def generate(self, request: LLMRequest) -> LLMResponse:
        body = {
            "model": self.model,
            "messages": request.messages,
            "temperature": request.temperature,
            "seed": 0,
            "max_tokens": request.max_tokens,
            "response_format": {"type": "json_schema",
                                "json_schema": {"name": "triage_decision", "schema": request.schema, "strict": True}},
        }
        data, latency = await self._post("/v1/chat/completions", body)
        try:
            text = data["choices"][0]["message"]["content"]
            usage = data.get("usage", {})
        except (KeyError, IndexError, TypeError) as exc:
            raise ProviderError("llamacpp: unexpected response shape") from exc
        return LLMResponse(text, self.name, self.model, usage.get("prompt_tokens", 0),
                           usage.get("completion_tokens", 0), latency)


class ReplayProvider:
    """Replays recorded responses from a JSONL cassette, keyed by provider/model + request.cache_key.

    With `inner`, a miss is generated by the inner provider and appended to the cassette, so the
    same class is the evaluation cache. Without `inner` (tests, CI), a miss raises ProviderError.
    """

    name = "replay"

    def __init__(self, cassette: str | Path, *, inner: LLMProvider | None = None, source: str | None = None):
        self.path = Path(cassette)
        self.inner = inner
        self.source = f"{inner.name}:{inner.model}" if inner else source
        if not self.source:
            raise ValueError("replay needs `inner` or `source` ('provider:model') to know what to replay")
        self.model = self.source.split(":", 1)[1]
        self._records: dict[str, dict[str, Any]] = {}
        self._lock = asyncio.Lock()
        if self.path.exists():
            for line in self.path.read_text().splitlines():
                if line.strip():
                    rec = json.loads(line)
                    self._records[rec["key"]] = rec

    def _key(self, request: LLMRequest) -> str:
        return f"{self.source}:{request.cache_key}"

    async def generate(self, request: LLMRequest) -> LLMResponse:
        key = self._key(request)
        rec = self._records.get(key)
        if rec is not None:
            return LLMResponse(rec["text"], rec["provider"], rec["model"], rec["prompt_tokens"],
                               rec["completion_tokens"], rec["latency_ms"], cached=True)
        if self.inner is None:
            raise ProviderError(f"replay: no recording for {key}")
        resp = await self.inner.generate(request)
        rec = {"key": key, "text": resp.text, "provider": resp.provider, "model": resp.model,
               "prompt_tokens": resp.prompt_tokens, "completion_tokens": resp.completion_tokens,
               "latency_ms": round(resp.latency_ms, 1)}
        async with self._lock:
            self._records[key] = rec
            self.path.parent.mkdir(parents=True, exist_ok=True)
            with self.path.open("a") as fh:
                fh.write(json.dumps(rec) + "\n")
        return resp

    async def aclose(self) -> None:
        if self.inner:
            await self.inner.aclose()


def build_provider(name: str, settings) -> LLMProvider:
    if name == "ollama":
        return OllamaProvider(settings.ollama_url, settings.ollama_model, settings.llm_timeout_seconds,
                              settings.llm_num_ctx)
    if name == "llamacpp":
        return LlamaServerProvider(settings.llamacpp_url, settings.llamacpp_model, settings.llm_timeout_seconds)
    if name.startswith("replay:"):  # e.g. replay:ollama:qwen3:4b-instruct
        return ReplayProvider(settings.replay_cassette, source=name.split(":", 1)[1])
    raise ValueError(f"unknown LLM provider {name!r}")
